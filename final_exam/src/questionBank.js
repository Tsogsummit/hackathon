function mcQuestion(group, topic, index, source) {
  const prompt = source[topic][index % source[topic].length];
  const variant = Math.floor(index / source[topic].length) + 1;
  return {
    id: `${group}-${TOPIC_SLUGS[topic]}-mc-${index + 1}`,
    grade_group: group,
    topic,
    type: "multiple_choice",
    question_text: variant === 1 ? prompt[0] : `${prompt[0]} ${variant}-р хувилбарын хамгийн зөв хариуг сонгоно уу.`,
    choices: prompt[1].map((text, choiceIndex) => ({ id: `c${choiceIndex + 1}`, text })),
    correct_answer: `c${prompt[2] + 1}`,
    explanation: `${topic} сэдвийн ойлголтыг бодит Python жишээгээр шалгана.`,
    difficulty: group === "grades_11_12" ? "дунд түвшин" : "анхан шат",
    points: 1,
    test_cases: [],
    starter_code: ""
  };
}

function codeQuestion(group, topic, index, source, points) {
  const [task, input, output] = source[topic][index % source[topic].length];
  const variant = Math.floor(index / source[topic].length) + 1;
  return {
    id: `${group}-${TOPIC_SLUGS[topic]}-code-${index + 1}`,
    grade_group: group,
    topic,
    type: "write_code",
    question_text: `${task}${variant > 1 ? ` ${variant}-р хувилбар: гаралтын форматыг яг адил хадгална.` : ""}\n\nОролтын формат: standard input.\nГаралтын формат: хүлээгдсэн тексттэй яг ижил байна.`,
    choices: [],
    correct_answer: "",
    explanation: `${topic} сэдвийн visible болон төстэй test case-уудаар автоматаар шалгана.`,
    difficulty: group === "grades_11_12" ? "дунд түвшин" : "анхан шат",
    points,
    test_cases: [
      { input, expected_output: output },
      { input, expected_output: output, sample: false, note: "Timeout болон тогтвортой гаралтыг шалгах давталтын case." }
    ],
    starter_code: "# Python шийдлээ энд бичнэ үү\n"
  };
}

export function buildQuestionBank() {
  const questions = [];
  questions.push(...buildGrade6QuestionBank());
  for (const topic of JUNIOR_TOPICS) {
    for (let index = 0; index < 16; index += 1) questions.push(mcQuestion("grades_7_8_9", topic, index, juniorMcPrompts));
    for (let index = 0; index < 4; index += 1) questions.push(codeQuestion("grades_7_8_9", topic, index, juniorCodeTasks, 3));
  }
  for (const topic of SENIOR_TOPICS) {
    for (let index = 0; index < 10; index += 1) questions.push(mcQuestion("grades_11_12", topic, index, seniorMcPrompts));
    for (let index = 0; index < 10; index += 1) questions.push(codeQuestion("grades_11_12", topic, index, seniorCodeTasks, 2));
  }
  return questions;
}

export function gradeGroupForGrade(grade) {
  if (Number(grade) === 6) return GRADE6_GROUP;
  if ([7, 8, 9].includes(Number(grade))) return "grades_7_8_9";
  if ([11, 12].includes(Number(grade))) return "grades_11_12";
  return null;
}

export function topicsForGroup(group) {
  if (group === GRADE6_GROUP) return GRADE6_TOPICS;
  if (group === "grades_7_8_9") return JUNIOR_TOPICS;
  if (group === "grades_11_12") return SENIOR_TOPICS;
  return [];
}
